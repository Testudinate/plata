-- ЧТО НАШЁЛ ПЕРВЫЙ ЖЕ ПРОГОН.
--
-- Тест not_null на cor_pct_annual упал: 2 строки с NULL. Разбор показал не
-- ошибку модели, а расхождение двух реализаций одной метрики:
--
--   V_COR_CANONICAL  ставит statement_num >= 2 в WHERE  → месяц, где нет ни
--                    одной выписки со вторым номером, исчезает целиком;
--   SV_COR и модель  зашивают фильтр ВНУТРЬ агрегата     → строка остаётся,
--                    знаменатель ноль, метрика NULL.
--
-- Затронуты два месяца — первый месяц жизни каждого продукта, где существуют
-- только первые выписки: CC 2024-07 (1 выписка) и GRZD_CLIPPED 2024-08 (3).
-- Утверждение S13 сравнивало семантическую вью с каноном ДЖОЙНОМ и поэтому
-- расхождения не видело: строка, которой нет с одной стороны, в джойн не
-- попадает. Класс дефекта ровно тот, о котором весь Part 2: «одна и та же»
-- метрика, реализованная трижды, расходится на краю.
--
-- Решение: строка с NULL хуже отсутствующей — дашборд покажет пустоту, агент
-- может принять её за ноль. Модель следует канону и месяц с неопределённым
-- COR не выпускает (HAVING на знаменатель), фильтр при этом остаётся внутри
-- агрегата. Тест not_null оставлен как сторож.
