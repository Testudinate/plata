-- ПРО ФАЙЛЫ НА СТЕЙДЖЕ. PUT из MCP-сессии недоступен, поэтому файлы проекта
-- записаны через COPY INTO ... SINGLE = TRUE — это пишет на стейдж ровно тот
-- текст и ровно под тем именем. Приём рабочий, но это обход: правильный
-- источник — git-репозиторий, см. 00b_bootstrap_copilot_accountadmin.sql.
