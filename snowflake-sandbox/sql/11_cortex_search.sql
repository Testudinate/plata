---------------------------------------------------------------------------
-- 11.1 DOC_RAW — приложения как текст.
--
-- Загружены все девять: A, B, C, D, E, F, G, H, I. Английские версии, потому
-- что вопросы к агенту приходят на английском, а перевод в момент поиска —
-- лишний шаг, на котором теряются точные имена колонок.
---------------------------------------------------------------------------

CREATE OR REPLACE TABLE RISK_GOV.AGENT.DOC_RAW (
    DOC_NAME   COMMENT 'Имя исходного документа',
    DOC_KIND   COMMENT 'appendix | assignment | governance',
    LOADED_AT  TIMESTAMP_NTZ DEFAULT SYSDATE(),
    CONTENT    COMMENT 'Полный текст документа как есть'
) COMMENT = 'Сырые документы контекста: приложения A-I как текст. Источник для чанкования и Cortex Search.';

-- INSERT-ы с телом каждого приложения здесь не воспроизводятся: девять
-- операторов по 3-5 КБ. В нормальной жизни источник — git-репозиторий
-- (см. 00b_bootstrap_copilot_accountadmin.sql), и содержимое приезжает
-- оттуда, а не набирается в SQL.
-- Проверка загрузки: SELECT COUNT(*) FROM RISK_GOV.AGENT.DOC_RAW;  -- 9


---------------------------------------------------------------------------
-- 11.2 DOC_CHUNKS — нарезка плюс контекст-слой в той же таблице.
--
-- Размер чанка 1200 символов с перехлёстом 200 подобран под структуру
-- приложений: типичный раздел («Sign Convention», «COR% Calculation») в него
-- помещается целиком, а перехлёст не даёт таблице с колонками разорваться
-- по границе.
---------------------------------------------------------------------------

CREATE OR REPLACE TABLE RISK_GOV.AGENT.DOC_CHUNKS
COMMENT = 'Чанки документации для Cortex Search. Два источника в одной поверхности: проза приложений и строки контекст-слоя. Агент ищет один раз и получает и объяснение, и контракт.'
AS
SELECT d.DOC_NAME     AS SOURCE_NAME,
       d.DOC_KIND     AS SOURCE_KIND,
       c.INDEX::INT   AS CHUNK_NO,
       c.VALUE::TEXT  AS CHUNK
FROM RISK_GOV.AGENT.DOC_RAW d,
     LATERAL FLATTEN(input => SNOWFLAKE.CORTEX.SPLIT_TEXT_RECURSIVE_CHARACTER(d.CONTENT, 'markdown', 1200, 200)) c
UNION ALL
SELECT 'RISK_GOV.AGENT.V_AGENT_CONTEXT', 'context_layer', 0,
       SECTION || ' | ' || KEY || ' | ' || CONTENT
FROM RISK_GOV.AGENT.V_AGENT_CONTEXT;

-- Замер: 36 чанков приложений (30 187 символов) + 50 строк контекст-слоя
-- (15 254 символа) = 86 записей, 45 441 символ.


---------------------------------------------------------------------------
-- 11.3 Сервис поиска.
--
-- TARGET_LAG сутки, а не минуты: документация меняется релизом, а каждый
-- рефреш будит warehouse. Тот же довод, по которому DMF в фазе 8 стоят на
-- суточном расписании.
---------------------------------------------------------------------------

CREATE OR REPLACE CORTEX SEARCH SERVICE RISK_GOV.AGENT.CS_RISK_DOCS
    ON CHUNK
    ATTRIBUTES SOURCE_NAME, SOURCE_KIND
    WAREHOUSE = COMPUTE_WH
    TARGET_LAG = '1 day'
    COMMENT = 'Поиск по документации риск-DWH: приложения A-I как проза плюс контекст-слой как строки.'
AS
SELECT CHUNK, SOURCE_NAME, SOURCE_KIND, CHUNK_NO FROM RISK_GOV.AGENT.DOC_CHUNKS;


